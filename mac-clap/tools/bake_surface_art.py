"""Prepare the static desktop panel artwork. Run with uv run --script."""
# /// script
# dependencies = ["pillow==13.0.0", "resvg-py==0.5.0"]
# ///
from io import BytesIO
from pathlib import Path
from xml.etree import ElementTree as ET

from PIL import Image, ImageFilter, ImageOps
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
SIZE = (640, 66)
LANCZOS = Image.Resampling.LANCZOS


def masthead():
    # Preserve the round glass city. Open up the sky and water at the outer
    # edges to give the title and the patch controls their own quiet space.
    photo = Image.open(ASSETS / "desktop-horizon.jpg").convert("RGB")
    w, h = photo.size
    cut = photo.crop((0, round(.12 * h), w, round(.80 * h)))
    scene = Image.new("RGB", SIZE)
    source = (0, round(.30 * w), round(.71 * w), w)
    dest = (0, 213, 337, SIZE[0])
    for i in range(3):
        region = cut.crop((source[i], 0, source[i + 1], cut.height))
        scene.paste(region.resize((dest[i + 1] - dest[i], SIZE[1]), LANCZOS), (dest[i], 0))

    # Render the original paths at desktop resolution, with an extruded edge,
    # a cool lower reflection and a white highlight across the face of the type.
    svg = ET.parse(ROOT.parent / "assets" / "wordmark.svg").getroot()
    group = next(iter(svg))
    group.set("stroke-width", "2.5")
    alpha = Image.open(BytesIO(resvg_py.svg_to_bytes(svg_string=ET.tostring(svg, encoding="unicode"), zoom=6))).getchannel("A")
    alpha = alpha.resize((174, 33), LANCZOS)
    shadow = Image.new("L", SIZE)
    shadow.paste(alpha, (13, 8))
    scene.paste((6, 47, 89), mask=shadow.filter(ImageFilter.GaussianBlur(1.4)))
    scene.paste((42, 112, 150), (12, 8), alpha)
    pearl = Image.new("RGB", alpha.size)
    for y in range(alpha.height):
        color = (252, 255, 255) if y < 20 else (194 + (y - 20) * 4, 235 + (y - 20), 251)
        pearl.paste(color, (0, y, alpha.width, y + 1))
    scene.paste(pearl, (12, 6), alpha)
    return scene


def motion_lens():
    photo = Image.open(ASSETS / "motion-glass.jpg").convert("RGB")
    # Map the measured outer rim to a 95-pixel circle. Its pixel center (60, 53)
    # is the field's X/Y origin, with 2.5 pixels beyond the full-depth orbit.
    # Fit the surrounding glass separately to retain the complete outer bevel.
    source_x = (0, 118, 1121, photo.width)
    source_y = (0, 46, 1060, photo.height)
    dest_x = (0, 13, 108, 120)
    dest_y = (0, 6, 101, 118)
    tile = Image.new("RGB", (120, 118))
    for row in range(3):
        for col in range(3):
            box = (source_x[col], source_y[row], source_x[col+1], source_y[row+1])
            size = (dest_x[col+1] - dest_x[col], dest_y[row+1] - dest_y[row])
            tile.paste(photo.resize(size, LANCZOS, box=box), (dest_x[col], dest_y[row]))
    return tile


def bitmap(out, name, image):
    width, height = image.size
    out.write(f"inline constexpr uint32_t {name}[{width} * {height}] = {{\n")
    pixels = [f"0xff{r:02x}{g:02x}{b:02x}" for r, g, b in image.convert("RGB").get_flattened_data()]
    for i in range(0, len(pixels), 12):
        out.write("    " + ",".join(pixels[i:i + 12]) + ",\n")
    out.write("};\n")


with (ROOT / "src/ui/desktop_art.h").open("w") as out:
    out.write("// Generated by mac-clap/tools/bake_surface_art.py.\n#pragma once\n#include <cstdint>\nnamespace reverie::desktopArt {\n")
    bitmap(out, "masthead", masthead())
    bitmap(out, "glass", ImageOps.fit(Image.open(ASSETS / "aqua-glass.jpg"), (320, 183), method=LANCZOS))
    bitmap(out, "lens", motion_lens())
    bitmap(out, "tank", ImageOps.fit(Image.open(ROOT.parent / "assets/aquarium.jpg"), (103, 63), method=LANCZOS))
    out.write("}\n")
