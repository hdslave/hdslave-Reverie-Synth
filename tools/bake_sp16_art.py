"""Bake Reverie's SP-16 artwork from the desktop panel sources."""
# /// script
# dependencies = ["pillow==13.0.0", "resvg-py==0.5.0"]
# ///
from io import BytesIO
from pathlib import Path
from runpy import run_path

import resvg_py
from PIL import Image, ImageDraw, ImageFont, ImageOps

from bake_screen_art import array

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
DESKTOP = ROOT / "mac-clap"
OUTPUT = ROOT / "build" / "sp16_art.h"
LANCZOS = Image.Resampling.LANCZOS


def motion_lens():
    photo = Image.open(ASSETS / "sp16-motion-glass.jpg").convert("RGB")
    # Use the desktop bake's measured rim and preserve the bezel independently.
    # At this size the rim is a 118 px circle centered on (75, 67).
    source_x = (0, 118, 1121, photo.width)
    source_y = (0, 46, 1060, photo.height)
    dest_x = (0, 16, 134, 150)
    dest_y = (0, 8, 126, 150)
    tile = Image.new("RGB", (150, 150))
    for row in range(3):
        for col in range(3):
            box = (source_x[col], source_y[row], source_x[col + 1], source_y[row + 1])
            size = (dest_x[col + 1] - dest_x[col], dest_y[row + 1] - dest_y[row])
            tile.paste(
                photo.resize(size, Image.Resampling.LANCZOS, box=box),
                (dest_x[col], dest_y[row]),
            )
    return tile


def bitmap(out, name, im):
    values = [f"0xff{r:02x}{g:02x}{b:02x}" for r, g, b in im.convert("RGB").get_flattened_data()]
    array(out, "uint32_t", name, values)


OUTPUT.parent.mkdir(exist_ok=True)
with OUTPUT.open("w") as out:
    out.write("// Generated by tools/bake_sp16_art.py.\n#pragma once\n#include <cstdint>\nnamespace reverie::sp16Art {\n")
    masthead = run_path(str(DESKTOP / "tools" / "bake_surface_art.py"))["masthead"]()
    bitmap(out, "header", masthead.resize((780,80), LANCZOS))
    water = ImageOps.fit(Image.open(DESKTOP / "assets" / "aqua-glass.jpg"), (780,171), LANCZOS)
    bitmap(out, "water", Image.blend(water.convert("RGB"), Image.new("RGB", water.size, "#d6f6ef"), .40))
    bitmap(out, "lens", motion_lens())
    fish = ImageOps.fit(Image.open(ASSETS / "aquarium.jpg"), (148,126), LANCZOS, centering=(.5,.26))
    bitmap(out, "tank", fish)
    lenses = Image.open(BytesIO(resvg_py.svg_to_bytes(svg_path=str(ASSETS / "sp16-section-lens.svg"), zoom=4)))
    cell = lenses.width // 2
    for i, name in enumerate(("sectionIdle", "sectionLit")):
        lens = lenses.crop((i * cell, 0, (i + 1) * cell, lenses.height)).resize((12, 26), LANCZOS).convert("RGBA")
        argb = [f"0x{a:02x}{r:02x}{g:02x}{b:02x}" for r, g, b, a in lens.get_flattened_data()]
        array(out, "uint32_t", name, argb)
    for size in (11, 14, 18):
        font = ImageFont.truetype(ASSETS / "Barlow-SemiBold.ttf", size)
        widths, offsets, coverage = [], [], []
        for ch in map(chr, range(32, 127)):
            width = max(1, round(font.getlength(ch)), font.getbbox(ch)[2])
            mask = Image.new("L", (width, size + 3))
            ImageDraw.Draw(mask).text((0, 0), ch, font=font, fill=255)
            offsets.append(len(coverage))
            widths.append(width)
            coverage.extend(mask.get_flattened_data())
        array(out, "uint8_t", f"width{size}", list(map(str, widths)))
        array(out, "uint16_t", f"offset{size}", list(map(str, offsets)))
        array(out, "uint8_t", f"mask{size}", list(map(str, coverage)))
    out.write("}\n")
