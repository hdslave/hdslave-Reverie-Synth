from io import BytesIO
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUTPUT = ROOT / "src" / "ui" / "screen_art.h"


def banner():
    scene = Image.open(ASSETS / "horizon.jpg").convert("RGB")
    # Keep the terrarium round. Extend the open sky at the left for the title and live patch details.
    scene = scene.resize((150, 50), Image.Resampling.LANCZOS).crop((0, 3, 150, 46))
    sky = scene.crop((0, 0, 1, 43)).resize((320, 43))
    sky.paste(scene, (170, 0))
    for x in range(sky.width):
        for y in range(sky.height):
            shade = min(1, max(0, (221 - x) / 52)) * (0.23 + 0.53 * (y / 42) ** 2)
            original = sky.getpixel((x, y))
            sky.putpixel((x, y), tuple(round(ch * (1 - shade) + tint * shade)
                                        for ch, tint in zip(original, (4, 36, 71))))
    mark = Image.open(BytesIO(resvg_py.svg_to_bytes(svg_path=str(ASSETS / "wordmark.svg"), zoom=4)))
    alpha = mark.getchannel("A").resize((128, 24), Image.Resampling.LANCZOS)
    sky.paste((3, 49, 93), (8, 3), alpha)
    sky.paste((251, 255, 255), (7, 2), alpha)
    return sky


def array(out, ctype, name, values, cols=16):
    out.write(f"inline constexpr {ctype} {name}[] = {{\n")
    for start in range(0, len(values), cols):
        out.write("    " + ", ".join(values[start:start+cols]) + ",\n")
    out.write("};\n")


def bitmap(out, name, im):
    words = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in im.convert("RGB").get_flattened_data()]
    array(out, "uint16_t", name, [f"0x{w:04x}" for w in words])


def font(out, size):
    face = ImageFont.truetype(ASSETS / "Barlow-SemiBold.ttf", size)
    widths, offsets, pixels = [], [], []
    for code in range(32, 127):
        char = chr(code)
        width = max(round(face.getlength(char)), face.getbbox(char)[2], 1)
        glyph = Image.new("L", (width, size + 2))
        ImageDraw.Draw(glyph).text((0, size - 2), char, font=face, anchor="ls", fill=255)
        widths.append(str(width))
        offsets.append(str(len(pixels)))
        pixels.extend(str(a) for a in glyph.get_flattened_data())
    array(out, "uint8_t", f"width{size}", widths)
    array(out, "uint16_t", f"offset{size}", offsets)
    array(out, "uint8_t", f"mask{size}", pixels, 32)


if __name__ == "__main__":
    with OUTPUT.open("w") as out:
        out.write("// Generated by tools/bake_screen_art.py from assets/.\n#pragma once\n#include <cstdint>\nnamespace hdui::art {\n")
        bitmap(out, "horizon", banner())
        tank = ImageOps.fit(Image.open(ASSETS / "aquarium.jpg"), (103, 99), method=Image.Resampling.LANCZOS)
        bitmap(out, "aquarium", tank)
        for size in (10, 12):
            font(out, size)
        out.write("} // namespace hdui::art\n")
