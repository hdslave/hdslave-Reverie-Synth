"""Generate the performance lookup from the chord database's Markdown tables."""
import argparse
import re
from pathlib import Path


def generate(source):
    sets = []
    heading = re.compile(r"## (\d\d) (\w+)$")
    row = re.compile(r"\| (\d+) \| `([^`]+)` \| `[^`]+` \| `([\d ]+)` \|$")
    for line in source.splitlines():
        if match := heading.fullmatch(line):
            number, name = match.groups()
            if int(number) != len(sets) + 1:
                raise ValueError(f"Unexpected set {line}")
            sets.append((name, []))
        elif match := row.fullmatch(line):
            index, symbol, pitches = match.groups()
            notes = list(map(int, pitches.split()))
            pads = sets[-1][1]
            if int(index) != len(pads) + 1 or not 3 <= len(notes) <= 5 or notes != sorted(set(notes)) or not 0 < notes[0] <= notes[-1] < 116:
                raise ValueError(f"Unexpected pad {line}")
            root, quality, bass = re.fullmatch(r"([A-G][b#]?)(.*?)(?:/([A-G][b#]?))?", symbol).groups()
            pads.append((root, quality, bass or "", notes))
    if len(sets) != 18 or any(len(pads) != 16 for _, pads in sets):
        raise ValueError("Expected 18 complete sets of 16 pads")
    lines = ["// Generated by tools/make_moods.py. The notes above each bass are semitone offsets.",
             "#pragma once", "", "#include <cstdint>", "", "namespace reverie", "{",
             "inline constexpr const char* moodNames[] = {", '    "Off",']
    lines.extend(f'    "{name}",' for name, _ in sets)
    lines.extend(["};", "constexpr int moodCount = sizeof (moodNames) / sizeof (moodNames[0]) - 1;",
                  "", "struct MoodPad", "{", "    const char* root;", "    const char* quality;",
                  "    const char* slashBass;", "    uint8_t bassNote, count, upper[4];",
                  "};", "", "inline constexpr MoodPad moodPads[moodCount][16] = {"])
    for name, pads in sets:
        lines.append(f"    {{ // {name}")
        for root, quality, bass, notes in pads:
            intervals = ", ".join(str(n - notes[0]) for n in notes[1:])
            lines.append(f'        {{ "{root}", "{quality}", "{bass}", {notes[0]}, {len(notes)}, {{ {intervals} }} }},')
        lines.append("    },")
    lines.extend(["};", "} // namespace reverie", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("database", type=Path)
    args = parser.parse_args()
    print(generate(args.database.read_text()), end="")
